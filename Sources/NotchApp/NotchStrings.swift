    let lang = NotchSettings.shared.langCode
    return NotchStrings.table[lang]?[key]
        ?? NotchStrings.table["es"]?[key]
        ?? key
}

func tr(_ key: String, _ args: CVarArg...) -> String {
    String(format: tr(key), arguments: args)
}

