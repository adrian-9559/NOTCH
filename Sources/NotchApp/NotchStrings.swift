// MARK: - Idiomas de NOTCH (ES/EN/FR/DE), configurables en Ajustes.
// Los títulos de pestaña son IDs estables (el orden guardado no se rompe).

enum NotchLang: String, CaseIterable {
    case es, en, fr, de

    var label: String {
        switch self {
        case .es: return "Español"
        case .en: return "English"
        case .fr: return "Français"
        case .de: return "Deutsch"
        }
    }

    /// ID del sistema si lo soportamos.
    static func system() -> NotchLang {
        guard let code = Locale.current.language.languageCode?.identifier else { return .es }
        return NotchLang(rawValue: code) ?? .es
    }
}

/// IDs estables de pestaña (lo que se guarda en Ajustes).
enum NotchTab: String, CaseIterable {
    case shelf, focus, mac, activity, music, notes

    /// Título visible según el idioma.
    var title: String { tr("tab.\(rawValue)") }

    var icon: String {
        switch self {
        case .shelf: return "tray"
        case .focus: return "timer"
        case .mac: return "cpu"
        case .activity: return "chart.bar"
        case .music: return "music.note"
        case .notes: return "note.text"
        }
    }
}

